// --- タイプ1:ソルジャー(基準の形)---------------------------------
function buildSoldierFighter(C) {
  const ship = new THREE.Group();

  // ※ 機首は自機と同じ「-Z が前」に揃えてある。
  //    こうしておくと Three.js の lookAt(相手の位置) がそのまま
  //    「相手の方へ機首を向ける」になり、AIの向き制御が素直に書ける。

  // --- 胴体 ---
  // ConeGeometry(底面の半径, 高さ, 何角形にするか)。4 = 四角錐 = かなり角ばる
  const bodyGeo = new THREE.ConeGeometry(0.75, 3.0, 4);
  // 円錐は初期状態で上(+Y)を向いているので、90度倒して前(-Z)へ向ける
  bodyGeo.rotateX(-Math.PI / 2);
  ship.add(createFlatPart(bodyGeo, C.BODY, C.EDGE));

  // --- 主翼(左右)---
  // BoxGeometry(幅, 高さ, 奥行き)
  // 細長すぎると1本の棒に見えてしまうので、奥行き(前後の厚み)をしっかり取る
  for (const side of [-1, 1]) {          // -1=左 / +1=右 をまとめて作る
    const wing = createFlatPart(new THREE.BoxGeometry(1.8, 0.16, 1.7), C.WING, C.EDGE);
    wing.position.set(side * 1.3, -0.1, 0.5);
    wing.rotation.z = side * 0.20;       // 少し上に反らせて「への字」の翼にする
    wing.rotation.y = side * 0.16;       // 後退角(翼を後ろへ倒す)
    ship.add(wing);
  }

  // --- 前翼(カナード)---
  // 機首寄りに小さな翼を付けると、一気に「兵器らしい」シルエットになる。
  // 自機は前翼を持たないので、遠目でも敵味方を形で見分けられる。
  for (const side of [-1, 1]) {
    const canard = createFlatPart(new THREE.BoxGeometry(0.85, 0.10, 0.55), C.WING, C.EDGE);
    canard.position.set(side * 0.72, 0.05, -0.85);
    canard.rotation.z = side * 0.34;     // 大きく上へ跳ね上げる
    canard.rotation.y = side * -0.10;    // 前進翼(自機の後退翼と逆)
    ship.add(canard);
  }

  // --- 双垂直尾翼(外側へ倒す)---
  for (const side of [-1, 1]) {
    const fin = createFlatPart(new THREE.BoxGeometry(0.12, 0.95, 0.9), C.WING, C.EDGE);
    fin.position.set(side * 0.5, 0.5, 1.15);
    fin.rotation.z = side * -0.36;       // ハの字に開く
    ship.add(fin);
  }

  // --- 側面の装甲板 ---
  for (const side of [-1, 1]) {
    const plate = createFlatPart(new THREE.BoxGeometry(0.16, 0.52, 1.9), C.WING, C.EDGE);
    plate.position.set(side * 0.55, -0.02, 0.15);
    plate.rotation.z = side * -0.22;
    ship.add(plate);
  }

  // --- 機首のセンサーポッド ---
  const pod = createFlatPart(new THREE.OctahedronGeometry(0.22), C.CANOPY, C.EDGE);
  pod.position.set(0, -0.18, -1.25);
  pod.scale.set(0.8, 0.8, 1.8);
  ship.add(pod);

  // --- エンジン(左右)---
  for (const side of [-1, 1]) addEnemyEngine(ship, C, side * 0.62, -0.05, 1.3, 0.36, 1.0);

  // --- コックピット(八面体。角ばったキャノピー)---
  const canopy = createFlatPart(new THREE.OctahedronGeometry(0.42), C.CANOPY, C.EDGE);
  canopy.position.set(0, 0.36, -0.15);
  canopy.scale.set(1, 0.7, 1.6);        // 前後に伸ばして流線形っぽく
  ship.add(canopy);

  return ship;
}

// --- タイプ2:ハウンド(突撃機)-------------------------------------
//
// 「短く、詰まっていて、前が重い」形。翼を大きく後ろへ畳み、
// 機首に顎のような吸気口を開かせて、噛みつきに来る印象を作る。
// 尾翼は付けない ― 安定させる形は、この機体の役目と逆だから。
function buildHoundFighter(C) {
  const ship = new THREE.Group();

  // --- 胴体:太く短い ---
  const bodyGeo = new THREE.ConeGeometry(0.92, 2.3, 4);
  bodyGeo.rotateX(-Math.PI / 2);
  ship.add(createFlatPart(bodyGeo, C.BODY, C.EDGE));

  // --- 顎(機首の左右へ突き出した吸気口)---
  // 細く長い板を、前ほど外へ開くように傾けて2枚。
  // 太い塊にすると胴体と一体化して「ただの塊」に見えてしまうので、
  // わざと薄くして、機首より前へはみ出させる。これがこの機体の顔になる。
  for (const side of [-1, 1]) {
    const jaw = createFlatPart(new THREE.BoxGeometry(0.20, 0.52, 2.0), C.WING, C.EDGE);
    jaw.position.set(side * 0.60, -0.10, -1.05);
    jaw.rotation.y = side * -0.34;      // 前が外に開く = 口を開けた形
    jaw.rotation.z = side * 0.20;
    ship.add(jaw);
  }

  // --- 主翼:大きく後退させ、下へ垂らす(獲物に覆いかぶさる形)---
  // 爪は翼の子として付ける。こうすると後退角を変えても
  // 勝手に翼の先端に付いてきてくれる(位置を計算し直さなくてよい)。
  for (const side of [-1, 1]) {
    const wing = createFlatPart(new THREE.BoxGeometry(2.3, 0.11, 1.0), C.WING, C.EDGE);
    wing.position.set(side * 1.35, -0.22, 0.75);
    wing.rotation.z = side * -0.34;     // 下へ垂らす(ソルジャーは上へ反らせている)
    wing.rotation.y = side * 0.52;      // 強い後退角
    ship.add(wing);

    const claw = createFlatPart(new THREE.ConeGeometry(0.13, 0.9, 3), C.CANOPY, C.EDGE);
    claw.position.set(side * 1.1, 0, -0.35);   // 翼から見た先端の少し前
    claw.rotation.x = -Math.PI / 2;            // 前へ尖らせる
    wing.add(claw);
  }

  // --- 背びれ ---
  // こぶ(箱)にすると背中が膨らんで鈍く見える。
  // 薄い板を1枚立てるだけのほうが、速そうなシルエットになる。
  const spine = createFlatPart(new THREE.BoxGeometry(0.12, 0.52, 1.7), C.WING, C.EDGE);
  spine.position.set(0, 0.52, 0.5);
  spine.rotation.x = 0.10;
  ship.add(spine);

  // --- 大型エンジン2基。ソルジャーより太く、外に開いて付ける ---
  for (const side of [-1, 1]) addEnemyEngine(ship, C, side * 0.72, -0.02, 1.15, 0.50, 1.3);

  // --- コックピット:小さく、前寄り ---
  const canopy = createFlatPart(new THREE.OctahedronGeometry(0.34), C.CANOPY, C.EDGE);
  canopy.position.set(0, 0.34, -0.42);
  canopy.scale.set(1, 0.62, 1.4);
  ship.add(canopy);

  return ship;
}

// --- タイプ3:スナイパー(狙撃機)-----------------------------------
//
// 「長く、細く、正面から見て薄い」形。上面を貫く砲身と、
// グライダーのように長く真っ直ぐな翼で、遠くから狙う機体だと分かる。
// 正面投影が小さい = 遠距離では当てにくい相手でもある。
function buildSniperFighter(C) {
  const ship = new THREE.Group();

  // --- 胴体:細く長い ---
  const bodyGeo = new THREE.ConeGeometry(0.52, 4.0, 4);
  bodyGeo.rotateX(-Math.PI / 2);
  bodyGeo.translate(0, 0, 0.3);          // 少し後ろへ寄せて、砲身を前に出す
  ship.add(createFlatPart(bodyGeo, C.BODY, C.EDGE));

  // --- 砲身:機体の上を前後に貫く長い角材 ---
  // この機体でいちばん目を引く部分。撃つ前にここが光る
  const barrel = createFlatPart(new THREE.BoxGeometry(0.26, 0.26, 4.6), C.WING, C.EDGE);
  barrel.position.set(0, 0.34, -0.5);
  ship.add(barrel);

  // 砲口(先端を一回り太くして、砲身だと分かるようにする)
  const muzzle = createFlatPart(new THREE.CylinderGeometry(0.20, 0.26, 0.5, 6), C.CANOPY, C.EDGE);
  muzzle.rotation.x = Math.PI / 2;
  muzzle.position.set(0, 0.34, -2.65);
  ship.add(muzzle);

  // --- 主翼:長く薄い直線翼(後退角なし)---
  for (const side of [-1, 1]) {
    const wing = createFlatPart(new THREE.BoxGeometry(3.1, 0.10, 0.85), C.WING, C.EDGE);
    wing.position.set(side * 1.85, -0.06, 0.75);
    wing.rotation.z = side * 0.06;       // ほぼ水平。安定した射撃台の形
    ship.add(wing);
  }

  // --- 翼端の垂直板 ---
  for (const side of [-1, 1]) {
    const tip = createFlatPart(new THREE.BoxGeometry(0.08, 0.62, 0.7), C.WING, C.EDGE);
    tip.position.set(side * 3.3, 0.22, 0.75);
    ship.add(tip);
  }

  // --- センサーの箱(キャノピーの後ろ)---
  // 遠くを見るための装置。これがあると「観測して撃つ機体」に見える
  const sensor = createFlatPart(new THREE.BoxGeometry(0.62, 0.46, 0.9), C.CANOPY, C.EDGE);
  sensor.position.set(0, 0.30, 0.75);
  ship.add(sensor);

  // --- 尾翼:1枚だけ、背が高い ---
  const fin = createFlatPart(new THREE.BoxGeometry(0.10, 1.25, 1.0), C.WING, C.EDGE);
  fin.position.set(0, 0.72, 1.85);
  ship.add(fin);

  // --- エンジンは1基だけ(遅い機体)---
  addEnemyEngine(ship, C, 0, -0.14, 1.75, 0.40, 1.1);

  // --- コックピット:細く前寄り ---
  const canopy = createFlatPart(new THREE.OctahedronGeometry(0.34), C.CANOPY, C.EDGE);
  canopy.position.set(0, 0.14, -0.55);
  canopy.scale.set(0.85, 0.62, 1.9);
  ship.add(canopy);

  return ship;
}

// ===================================================================
// 自機を組み立てる
//
// 三人称視点では機体を「後ろから」見ることになるので、
// 後部(エンジンノズル・噴射光)を強めに作ると形が読み取りやすい。
// 敵機と違い、機首は -Z(画面の奥)を向ける。
// ===================================================================
function createPlayerFighter() {
  const ship = new THREE.Group();

  // --- 胴体 ---
  const bodyGeo = new THREE.ConeGeometry(0.55, 2.8, 5);
  bodyGeo.rotateX(-Math.PI / 2);   // +Y を向いている円錐を -Z(前方)へ倒す
  ship.add(createFlatPart(bodyGeo, PLAYER.BODY_COLOR, PLAYER.EDGE_COLOR));

  // --- 主翼(左右)---
  for (const side of [-1, 1]) {
    const wingGeo = new THREE.BoxGeometry(1.7, 0.14, 1.5);
    const wing = createFlatPart(wingGeo, PLAYER.WING_COLOR, PLAYER.EDGE_COLOR);
    wing.position.set(side * 1.2, -0.08, 0.5);
    wing.rotation.z = side * -0.18;   // 少し下に反らせる(敵機と逆にして印象を変える)
    wing.rotation.y = side * 0.16;    // 後退角
    ship.add(wing);
  }

  // --- 機関砲ポッドと砲身(左右)---
  // BOLT.OFFSET_* が指す発射口を、目に見える部品として置いてある。
  // モデル座標 = 世界座標 ÷ PLAYER.SCALE(0.85) なので、
  //   世界 (±1.62, -0.15, -1.20) → モデル (±1.91, -0.18, -1.41)
  // 砲身の先がちょうどそこに来るよう寸法を決めている。
  // 「弾がどこから出ているか」が機体の形として説明される。
  for (const side of [-1, 1]) {
    const podGeo = new THREE.BoxGeometry(0.26, 0.24, 1.5);
    const pod = createFlatPart(podGeo, PLAYER.WING_COLOR, PLAYER.EDGE_COLOR);
    pod.position.set(side * 1.88, -0.20, -0.30);   // 主翼の外寄りに載せる
    pod.rotation.z = side * -0.18;                 // 翼の反りに合わせる
    ship.add(pod);

    const barrelGeo = new THREE.BoxGeometry(0.11, 0.11, 0.55);
    const barrel = createFlatPart(barrelGeo, PLAYER.BODY_COLOR, PLAYER.EDGE_COLOR);
    barrel.position.set(side * 1.90, -0.19, -1.25);
    ship.add(barrel);
  }

  // --- 機首のストレーキ(左右の張り出し)---
  // 円錐のままだと丸い鉛筆に見えるので、平たい板で角を作って
  // 「削り出した機首」に見せる。板1枚ぶんの面数で印象が大きく変わる。
  for (const side of [-1, 1]) {
    const strakeGeo = new THREE.BoxGeometry(0.55, 0.07, 1.5);
    const strake = createFlatPart(strakeGeo, PLAYER.WING_COLOR, PLAYER.EDGE_COLOR);
    strake.position.set(side * 0.45, -0.06, -0.60);
    strake.rotation.y = side * 0.10;
    ship.add(strake);
  }

  // --- 背骨(ドーサルスパイン)---
  // 胴体の上に稜線を1本通すと、後ろから見たときに真ん中が締まって見える。
  const spineGeo = new THREE.BoxGeometry(0.24, 0.26, 1.7);
  const spine = createFlatPart(spineGeo, PLAYER.WING_COLOR, PLAYER.EDGE_COLOR);
  spine.position.set(0, 0.30, 0.60);
  ship.add(spine);

  // --- 双垂直尾翼(内側へ倒す)---
  // 敵機は外へ開いた双尾翼にしてあるので、こちらは内へ倒して形を対にする。
  for (const side of [-1, 1]) {
    const finGeo = new THREE.BoxGeometry(0.11, 0.85, 0.85);
    const fin = createFlatPart(finGeo, PLAYER.WING_COLOR, PLAYER.EDGE_COLOR);
    fin.position.set(side * 0.46, 0.48, 1.10);
    fin.rotation.z = side * 0.30;
    ship.add(fin);
  }

  // --- エンジンノズルと噴射光(左右)---
  for (const side of [-1, 1]) {
    const nozzleGeo = new THREE.CylinderGeometry(0.26, 0.32, 0.9, 6);
    nozzleGeo.rotateX(Math.PI / 2);
    const nozzle = createFlatPart(nozzleGeo, PLAYER.WING_COLOR, PLAYER.EDGE_COLOR);
    nozzle.position.set(side * 0.55, -0.02, 1.25);
    ship.add(nozzle);

    // 噴射光。速度に応じて後ろへ伸ばすので、あとで触れるよう配列に控えておく。
    // MeshBasicMaterial = 光の影響を受けずに自分で光る材質。炎の表現向き。
    const glowGeo = new THREE.ConeGeometry(0.22, 1.6, 6);
    glowGeo.rotateX(Math.PI / 2);      // 後ろ(+Z)へ尖らせる
    glowGeo.translate(0, 0, 0.8);      // 円錐の根元がノズル口に来るようずらす
    const glowMat = new THREE.MeshBasicMaterial({
      color: 0x8fd8ff, transparent: true, opacity: 0.6,
    });
    const glow = new THREE.Mesh(glowGeo, glowMat);
    glow.position.set(side * 0.55, -0.02, 1.6);
    ship.add(glow);
    engineGlows.push(glow);
  }

  // --- キャノピー ---
  const canopyGeo = new THREE.OctahedronGeometry(0.36);
  const canopy = createFlatPart(canopyGeo, PLAYER.CANOPY_COLOR, PLAYER.EDGE_COLOR);
  canopy.position.set(0, 0.3, -0.2);
  canopy.scale.set(1, 0.65, 1.7);
  ship.add(canopy);

  ship.scale.setScalar(PLAYER.SCALE);
  return ship;
}

// ===================================================================
// コックピットの内装を組み立てる
//
// 参考:スターフォックス64のコックピットモード。
// 「囲まれている」と感じるのは、視界の下と左右が機体の内側で塞がれているから。
// そこで計器台・左右の支柱・上枠の4つで画面の縁を物理的に埋める。
//
// 材質は MeshBasicMaterial(光の影響を受けない単色)を使う。
// 機内は本来暗いので、太陽の向きで明るさが変わってしまうと不自然なため。
// ===================================================================
function createSilhouette(points) {
  // Shape = 平面の輪郭。点を順につないで閉じると、その内側が面になる。
  const shape = new THREE.Shape();
  shape.moveTo(points[0][0], points[0][1]);
  for (let i = 1; i < points.length; i++) shape.lineTo(points[i][0], points[i][1]);
  shape.closePath();

  const mesh = new THREE.Mesh(
    new THREE.ShapeGeometry(shape),
    new THREE.MeshBasicMaterial({ color: COCKPIT.COLOR, side: THREE.DoubleSide })
  );

  // 輪郭線。ほぼ黒のシルエットなので、形を伝えるのはこの線だけ。
  const linePoints = points.map((pt) => new THREE.Vector3(pt[0], pt[1], 0));
  linePoints.push(linePoints[0].clone());   // 最後に始点へ戻して閉じる
  mesh.add(new THREE.Line(
    new THREE.BufferGeometry().setFromPoints(linePoints),
    new THREE.LineBasicMaterial({
      color: COCKPIT.EDGE, transparent: true, opacity: COCKPIT.EDGE_OPACITY,
    })
  ));

  return mesh;
}

function createCockpitInterior() {
  const g = new THREE.Group();

  // --- 計器台(台形)---
  // 「縦横1」の大きさで作っておき、毎コマ画面に合わせて拡大縮小する。
  // 下辺を広く、上辺を狭くすると台形になる。
  const t = COCKPIT.DASH_TAPER * 0.5;
  const dash = createSilhouette([
    [-0.5, -0.5], [0.5, -0.5], [t, 0.5], [-t, 0.5],
  ]);
  g.add(dash);

  // --- 計器の輝点 ---
  // 計器台の子にして、台の拡大縮小をそのまま受け継がせる。
  // 天面のすぐ内側に一列っぽく散らす。
  const glintCount = 18;
  const glintPos = new Float32Array(glintCount * 3);
  for (let i = 0; i < glintCount; i++) {
    glintPos[i * 3 + 0] = (Math.random() - 0.5) * (COCKPIT.DASH_TAPER * 0.88);
    glintPos[i * 3 + 1] = 0.5 - 0.10 - Math.random() * 0.16;
    glintPos[i * 3 + 2] = 0.01;   // 面よりほんの少し手前に出して隠れないようにする
  }
  const glintGeo = new THREE.BufferGeometry();
  glintGeo.setAttribute('position', new THREE.BufferAttribute(glintPos, 3));
  dash.add(new THREE.Points(glintGeo, new THREE.PointsMaterial({
    color: COCKPIT.GLINT, size: 2.5, sizeAttenuation: false,
    transparent: true, opacity: 0.7,
  })));

  // --- 左右の支柱 ---
  // 縦長の細い平面。傾けて視界の縁をかすめさせる。
  const pillars = [];
  for (const side of [-1, 1]) {
    const pillar = createSilhouette([
      [-0.5, -0.5], [0.5, -0.5], [0.5, 0.5], [-0.5, 0.5],
    ]);
    pillar.rotation.z = side * COCKPIT.PILLAR_LEAN * -1;
    g.add(pillar);
    pillars.push(pillar);
  }

  // --- 上辺の枠 ---
  const topBar = createSilhouette([
    [-0.5, -0.5], [0.5, -0.5], [0.5, 0.5], [-0.5, 0.5],
  ]);
  g.add(topBar);

  // --- 機首(ガラスの向こうに見える自機の先端)---
  // 台形。根元は計器台に隠れ、先端だけが上に出る。
  const noseTip = COCKPIT.NOSE_TIP * 0.5;
  const nose = createSilhouette([
    [-0.5, -0.5], [0.5, -0.5], [noseTip, 0.5], [-noseTip, 0.5],
  ]);
  g.add(nose);

  // --- 光像式照準器:土台 ---
  // 計器台から生えて、ガラス板を目の高さまで持ち上げる箱。
  //
  // ※ 既定では出さない。ガラス板より手前にあるため、計器盤の中央を
  //   縦に塞いでしまい、そこに置いた計器が読めなくなる。
  //   照準器は上から吊っている、という解釈にして柱をなくしてある。
  //   戻したいときは COCKPIT.SIGHT_BASE_SHOW を true に。
  const sightBase = createSilhouette([
    [-0.5, -0.5], [0.5, -0.5], [0.32, 0.5], [-0.32, 0.5],
  ]);
  sightBase.visible = !!COCKPIT.SIGHT_BASE_SHOW;
  g.add(sightBase);

  // --- 光像式照準器:ガラス板 ---
  //
  // sightPlane は「ガラス板の面そのもの」を表す入れ物。
  // 拡大縮小を縦横同じ倍率で掛けるので、この中に置いたものは形が歪まない。
  // 将来のロックオンマーカーも、この中に足せば同じ面の上を動く。
  const sightPlane = new THREE.Group();

  // ガラス。半透明。宇宙が透けて見えることが大事なので、かなり薄くする。
  // depthWrite: false で、奥のものを消してしまわないようにする。
  const sightGlass = new THREE.Mesh(
    new THREE.PlaneGeometry(1, 1),
    new THREE.MeshBasicMaterial({
      color: 0x8fd8ff,
      transparent: true,
      opacity: COCKPIT.SIGHT_GLASS_OPACITY,
      depthWrite: false,
      side: THREE.DoubleSide,
    })
  );
  sightGlass.add(new THREE.LineSegments(
    new THREE.EdgesGeometry(new THREE.PlaneGeometry(1, 1)),
    new THREE.LineBasicMaterial({ color: COCKPIT.EDGE, transparent: true, opacity: 0.8 })
  ));
  sightPlane.add(sightGlass);

  // --- レティクル(照準環)---
  // ガラスに光が投影されているように見せる。円+中心点+左右の目盛り。
  // depthTest: false で、常に手前に描く(ガラスに埋もれないように)。
  const reticleMat = new THREE.LineBasicMaterial({
    color: COCKPIT.RETICLE_COLOR, transparent: true,
    opacity: COCKPIT.RETICLE_OPACITY, depthTest: false,
  });
  const reticle = new THREE.Group();
  reticle.renderOrder = 10;   // 最後に描く = 何にも隠されない

  // 外側の円
  const ringPts = [];
  const RING_SEG = 40;
  for (let i = 0; i <= RING_SEG; i++) {
    const th = (i / RING_SEG) * Math.PI * 2;
    ringPts.push(new THREE.Vector3(Math.cos(th) * 0.5, Math.sin(th) * 0.5, 0));
  }
  reticle.add(new THREE.Line(new THREE.BufferGeometry().setFromPoints(ringPts), reticleMat));

  // 中心点(ごく小さな円)
  const dotPts = [];
  for (let i = 0; i <= 12; i++) {
    const th = (i / 12) * Math.PI * 2;
    dotPts.push(new THREE.Vector3(Math.cos(th) * 0.055, Math.sin(th) * 0.055, 0));
  }
  reticle.add(new THREE.Line(new THREE.BufferGeometry().setFromPoints(dotPts), reticleMat));

  // 左右と上の短い目盛り
  const tickPts = [
    new THREE.Vector3(-0.72, 0, 0), new THREE.Vector3(-0.52, 0, 0),
    new THREE.Vector3( 0.52, 0, 0), new THREE.Vector3( 0.72, 0, 0),
    new THREE.Vector3(0,  0.52, 0), new THREE.Vector3(0,  0.72, 0),
  ];
  reticle.add(new THREE.LineSegments(
    new THREE.BufferGeometry().setFromPoints(tickPts), reticleMat));

  sightPlane.add(reticle);
  g.add(sightPlane);

  // --- 計器台の上辺を走る縁取り ---
  // WebGLの線は太さを変えられない(常に1ピクセル)ため、
  // 「太い線」が欲しいときは細長い面を1枚置くのが確実。
  const trim = new THREE.Mesh(
    new THREE.PlaneGeometry(1, 1),
    new THREE.MeshBasicMaterial({ color: COCKPIT.EDGE, side: THREE.DoubleSide })
  );
  g.add(trim);

  // --- 計器の面(canvasを貼った板)---
  // ここが「重ねる」のをやめた本体。計器の絵を canvas に描き、
  // それを計器台の手前に1枚の板として置く。
  // 板は内装の一部なので、機体が揺れれば一緒に揺れ、傾ければ一緒に傾く。
  // 遠近も勝手に付く ― HTMLを重ねていたときは、どれも自前で作る必要があった。
  const faceTex = new THREE.CanvasTexture(initConsole3D());
  faceTex.minFilter = THREE.LinearFilter;   // 縮小時のちらつきを抑える
  faceTex.generateMipmaps = false;
  const face = new THREE.Mesh(
    new THREE.PlaneGeometry(1, 1),
    new THREE.MeshBasicMaterial({
      map: faceTex, transparent: true, depthWrite: false, depthTest: false,
    })
  );
  face.renderOrder = 6;
  g.add(face);

  // ===================================================================
  // 内装は「必ず手前」に描く
  //
  // 自分が乗っている機体の一部なので、外の景色が計器台の手前に
  // 出てくることはありえない。ところが弾は翼(目より後ろ)から出るので、
  // 計器台の面(目から2.0)より近い位置を通る一瞬があり、
  // 素直に奥行きで比べると弾が計器を突き抜けて見えてしまう。
  //
  // そこで内装は奥行きの判定をやめ、描く順番だけで前後を決める。
  //   計器台・支柱・上枠 … 5
  //   計器の面           … 6
  //   レティクル         … 10(いちばん手前。ガラスに映る光なので)
  // ===================================================================
  const alwaysFront = (obj, order) => {
    obj.renderOrder = order;
    if (obj.material) { obj.material.depthTest = false; obj.material.depthWrite = false; }
    for (const c of obj.children) alwaysFront(c, order);
  };
  alwaysFront(dash, 5);
  for (const p of pillars) alwaysFront(p, 5);
  alwaysFront(topBar, 5);
  alwaysFront(trim, 5);
  alwaysFront(nose, 4);     // 機首は計器台より奥。台に根元を隠させる
  alwaysFront(face, 6);

  // 毎コマの配置計算で使うので、部品を覚えておく
  g.userData = {
    dash: dash, pillars: pillars, topBar: topBar, trim: trim, nose: nose,
    sightBase: sightBase, sightPlane: sightPlane, sightGlass: sightGlass,
    reticle: reticle, reticleMat: reticleMat,
    face: face, faceTex: faceTex,
  };
  return g;
}

