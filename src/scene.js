// ===================================================================
// 再出撃:自機と敵を初期状態に戻す
// ===================================================================
function resetFlight() {
  if (!sceneReady) return;

  // 自機を原点・静止・正面向きへ
  playerShip.position.set(0, 0, 0);
  shipVelocity.set(0, 0, 0);
  shipQuat.identity();
  yawRate = 0;
  pitchRate = 0;
  rollRate = 0;
  visualRoll = 0;
  camSpeedEase = 0;
  drifting = false;
  burstCoast = 0;
  playerShip.quaternion.identity();
  camQuat.identity();

  // 飛んでいるものをすべて片付ける
  for (const m of missiles)   scene.remove(m.mesh);
  missiles.length = 0;
  for (const f of flares)   { scene.remove(f.mesh); f.coreMat.dispose(); f.haloMat.dispose(); }
  flares.length = 0;
  for (const b of bolts)      scene.remove(b.mesh);
  for (const b of enemyBolts) scene.remove(b.mesh);
  for (const d of debris)   { scene.remove(d.mesh); d.mesh.material.dispose(); }
  for (const o of ordnance) { scene.remove(o.mesh); o.mesh.material.dispose(); }
  for (const b of blasts)   { scene.remove(b.mesh); b.mesh.material.dispose(); }
  bolts.length = 0;
  enemyBolts.length = 0;
  debris.length = 0;
  ordnance.length = 0;
  blasts.length = 0;

  // 敵を全機復活させて前方に置き直す
  // 出撃のたびに敵を初期化する。
  // 最初の編成は抽選せず、3タイプを1機ずつ・順番だけ入れ替えて配る。
  // 抽選に任せると同じタイプが3機並ぶ出撃が出てしまい、
  // 「3種類いる」ということ自体が伝わらないため。
  // (撃墜後のリスポーンは均等な抽選に任せる)
  const lineup = shuffledArchetypes();
  enemies.forEach((e, i) => respawnEnemy(e, lineup[i % lineup.length]));
}

// エンジンの電力配分(0〜100%)から速度を決める
function speedFromEnginePower(enginePercent) {
  const ratio = Math.max(0, Math.min(100, enginePercent)) / 100;
  return PLAYER.MIN_SPEED + ratio * (PLAYER.MAX_SPEED - PLAYER.MIN_SPEED);
}

// ===================================================================
// 横滑り角(ドリフト角)
//
// 「機首が向いている向き」と「実際に進んでいる向き」のずれ。
// 通常飛行では0に近く、ドリフト中に大きく開く。
// 弾は機首方向へ飛ぶので、この角度が大きいほど
// 「進行方向とは違うところを撃っている」ことになる ― 振り向き撃ちの手がかり。
// ===================================================================
function driftAngleDeg() {
  if (!sceneReady) return 0;
  const speed = shipVelocity.length();
  if (speed < 0.5) return 0;             // 止まっているときは意味がない
  const forward = new THREE.Vector3(0, 0, -1).applyQuaternion(playerShip.quaternion);
  const dir = shipVelocity.clone().divideScalar(speed);
  const c = Math.max(-1, Math.min(1, forward.dot(dir)));
  return Math.acos(c) * 180 / Math.PI;
}

// ===================================================================
// いちばん近い敵との距離と接近率
//
// 接近率(closure)= 1秒あたり何メートル詰まっているか。
// プラスなら近づいている、マイナスなら離されている。
// 逃げ切れるのか、追いつけるのかが数字で分かる ― 上級者向けの読み。
// ===================================================================
function nearestTargetInfo() {
  if (!sceneReady) return { dist: 0, closure: 0, valid: false };

  let best = null, bestD = Infinity;
  for (const e of enemies) {
    if (!e.alive) continue;
    const d = e.group.position.distanceTo(playerShip.position);
    if (d < bestD) { bestD = d; best = e; }
  }
  if (!best) return { dist: 0, closure: 0, valid: false };

  // 自機から敵への単位ベクトルに、相対速度を投影する
  const toE = best.group.position.clone().sub(playerShip.position).normalize();
  const rel = shipVelocity.clone().sub(best.vel || new THREE.Vector3());
  return { dist: bestD, closure: rel.dot(toE), valid: true };
}

// 今のロール角(ラジアン)。水平からどれだけ傾いているか。
// 「機体の右」が世界の水平からどれだけ持ち上がっているかで測る。
function currentRoll() {
  if (!sceneReady) return 0;
  const right = new THREE.Vector3(1, 0, 0).applyQuaternion(playerShip.quaternion);
  const up    = new THREE.Vector3(0, 1, 0).applyQuaternion(playerShip.quaternion);
  return Math.atan2(right.y, up.y);
}

// 機首が水平からどれだけ上下しているか(ラジアン)
function currentPitch() {
  if (!sceneReady) return 0;
  const fwd = new THREE.Vector3(0, 0, -1).applyQuaternion(playerShip.quaternion);
  return Math.asin(Math.max(-1, Math.min(1, fwd.y)));
}

// 今の速度(単位/秒)。計器表示に使う
function currentSpeed() {
  return shipVelocity ? shipVelocity.length() : 0;
}

// ===================================================================
// 照準の状態を更新する(仕様:段階を持つ1つのシステムとして作る)
//
// 【考え方】
// 機首から前方へまっすぐ伸びる線を引き、敵の中心がその線からどれだけ
// 離れているかを測る。捕捉半径より近ければ「捉えている」。
//
// 当たり判定(ENEMY.HIT_RADIUS)とは別に捕捉半径を持たせているのが要点。
// 捕捉のほうを大きくしておくと、アイドル揺れ程度では捕捉が途切れない。
//
// 状態は 'CLEAR' → 'TRACKING' → 'LOCKED' の3段階。
//
// ただし LOCKED まで上がるのはミサイルを選んでいるときだけ(allowLock)。
// 機関砲やビームは「軽く捉えて偏差点を追う」だけで、ロックはしない。
//
// これは演出の都合ではなく、駆け引きの都合。
// ロックの警報が銃でも鳴ると、警報が鳴りっぱなしになって
// 「ロックされた ― フレアを切るか?」の判断そのものが成立しなくなる。
// 警報を鳴らすのはミサイルのときだけに絞ることで、
// 鳴った瞬間の重みを保つ。
// ===================================================================
function lockSeconds(sensorPercent) {
  const ratio = Math.max(0, Math.min(sensorPercent || 0, 100)) / 100;
  return AIM.LOCK_SEC_MAX + ratio * (AIM.LOCK_SEC_MIN - AIM.LOCK_SEC_MAX);
}

function updateAim(dt, sensorPercent, allowLock) {
  if (!sceneReady) { aimState = 'CLEAR'; return aimState; }

  const forward = new THREE.Vector3(0, 0, -1).applyQuaternion(playerShip.quaternion);

  // 捉えられる距離は索敵半径に縛られる(上限は CAPTURE_RANGE)。
  // センサーへ配るほど、遠くから仕掛けられるようになる。
  const captureRange = Math.min(
    AIM.CAPTURE_RANGE,
    sensorRange(sensorPercent) * AIM.LOCK_RANGE_MULT);

  let best = null;
  let bestAhead = Infinity;

  for (const e of enemies) {
    if (!e.alive) continue;

    const toEnemy = e.group.position.clone().sub(playerShip.position);

    // 前方への距離。マイナスなら後ろにいるので対象外
    const ahead = toEnemy.dot(forward);
    if (ahead <= 0 || ahead > captureRange) continue;

    // 照準線からの横のずれ。
    // 「敵へのベクトル」から「前方成分」を引くと、横方向のずれだけが残る。
    const offset = toEnemy.clone().addScaledVector(forward, -ahead).length();

    // 捕捉半径。遠いほど少し広げる(遠距離でも狙えるように)
    const captureRadius = ENEMY.HIT_RADIUS * AIM.CAPTURE_MULT + ahead * AIM.CAPTURE_SPREAD;

    if (offset < captureRadius && ahead < bestAhead) {
      best = e;
      bestAhead = ahead;
    }
  }

  // --- 状態遷移 ---
  // CLEAR(何もない) → TRACKING(捉えた) → LOCKED(ロック完了)
  if (best) {
    if (aimState === 'CLEAR') {
      aimState = 'TRACKING';   // 捉えた瞬間
      aimHoldTime = 0;
      lockProgress = 0;
    }
    aimTarget = best;
    aimHoldTime += dt;
    lockGrace = AIM.LOCK_KEEP;

    // ロックの進み。センサー配分が高いほど速く満ちる。
    // ミサイル以外を選んでいるときは進めない ― 捉えるだけで終わる。
    if (allowLock) {
      lockProgress = Math.min(lockProgress + dt / lockSeconds(sensorPercent), 1);
      if (lockProgress >= 1) aimState = 'LOCKED';
    } else {
      // ミサイルでロックしたまま銃に持ち替えると、ロックが残り続けてしまう。
      // 捉えている状態まで下げ直す。
      lockProgress = 0;
      if (aimState === 'LOCKED') aimState = 'TRACKING';
    }

  } else if (allowLock && lockGrace > 0 && aimState === 'LOCKED') {
    // 照準から外れても、少しの間はロックを保つ。
    // 揺れや一瞬の被弾でロックが飛ぶと、ミサイルが使い物にならないため。
    lockGrace -= dt;
    if (lockGrace <= 0) { aimState = 'CLEAR'; aimTarget = null; aimHoldTime = 0; lockProgress = 0; }

  } else {
    aimState = 'CLEAR';        // 外したら即座に戻る
    aimTarget = null;
    aimHoldTime = 0;
    lockProgress = 0;
    lockGrace = 0;
  }

  // --- レティクルの見た目に反映 ---
  const parts = cockpitInterior ? cockpitInterior.userData : null;
  if (parts && parts.reticleMat) {
    const capturing = (aimState !== 'CLEAR');
    parts.reticleMat.color.setHex(
      capturing ? COCKPIT.RETICLE_LOCK : COCKPIT.RETICLE_COLOR);
    parts.reticleMat.opacity =
      capturing ? COCKPIT.RETICLE_OPACITY_LOCK : COCKPIT.RETICLE_OPACITY;

    // ロック完了で照準環が縮む。狙いが定まった感じを出す
    if (parts.reticle) {
      const target = (aimState === 'LOCKED')
        ? COCKPIT.RETICLE_SIZE * 0.62 : COCKPIT.RETICLE_SIZE;
      const cur = parts.reticle.scale.x;
      parts.reticle.scale.setScalar(cur + (target - cur) * 0.25);
    }
  }

  return aimState;
}

