// ===================================================================
// センサー精度(仕様書9.3の7つ目)
// 索敵半径 = センサーの電力配分で決まる。配分0%でも最低限は見える。
// ===================================================================
function sensorRange(sensorPercent) {
  const ratio = Math.max(0, Math.min(100, sensorPercent)) / 100;
  return SENSOR.MIN_RANGE + ratio * (SENSOR.MAX_RANGE - SENSOR.MIN_RANGE);
}

// ===================================================================
// レーダーと敵マーカーのためのデータを作る
//
// 索敵半径の外にいる敵は、そもそもこの配列に入らない。
// = レーダーにも映らず、3D画面にもマーカーが出ない(仕様の4番)
//
// 返す値(敵1機ぶん):
//   localX / localZ … 自機から見た相対位置。localZ がマイナスなら前方
//   dist            … 距離
//   hot             … 熱で捕捉している敵か(発射直前・発射直後・被弾直後)
//   ndcX / ndcY     … 画面上の位置(-1〜+1)。マーカーを置くのに使う
//   inFront         … 画面の前方にいるか(後ろの敵にマーカーを出さないため)
// ===================================================================
function getContacts(sensorPercent) {
  const result = [];
  if (!sceneReady) return result;

  const range = sensorRange(sensorPercent);

  // 自機の向きの「逆回転」。これを掛けると、世界の座標が
  // 「自機から見た前後左右」に変換できる(機首が常に上のレーダーの要)
  const inverse = playerShip.quaternion.clone().invert();

  for (const e of enemies) {
    if (!e.alive) continue;

    const to = e.group.position.clone().sub(playerShip.position);
    const dist = to.length();

    // 熱を出している敵は、索敵半径の HEAT_BONUS 倍まで捕捉できる
    const hot = (e.telegraph > 0 || e.heatSig > 0);
    const limit = range * (hot ? SENSOR.HEAT_BONUS : 1);
    if (dist > limit) continue;   // 圏外。映らない

    const local = to.clone().applyQuaternion(inverse);

    // 画面上の位置を求める。project() は3Dの点を画面座標(-1〜+1)に変換する命令
    const ndc = e.group.position.clone().project(camera);
    // カメラから見て前方にあるか。z がマイナスならカメラの前
    const inFront = camera.worldToLocal(e.group.position.clone()).z < 0;

    result.push({
      localX: local.x,
      localY: local.y,     // 自機から見た上下。レーダーの ▲▼ に使う
      localZ: local.z,
      dist: dist,
      hot: hot,
      ndcX: ndc.x,
      ndcY: ndc.y,
      inFront: inFront,
    });
  }

  return result;
}

// ===================================================================
// 迫ってくる敵ミサイルのレーダー情報
//
// 敵機と同じ形で返すので、main.js は同じ描画処理を使い回せる。
// ミサイルは噴射で燃えているぶん、敵機より遠くから捉えられる
// (索敵半径に熱の補正 HEAT_BONUS をかけている)。
// ===================================================================
function missileContacts(sensorPercent) {
  const result = [];
  if (!sceneReady) return result;

  const range = sensorRange(sensorPercent) * SENSOR.HEAT_BONUS;
  const inverse = playerShip.quaternion.clone().invert();

  for (const m of missiles) {
    if (!m.fromEnemy) continue;      // 自機に向かってくるものだけ

    const to = m.mesh.position.clone().sub(playerShip.position);
    const dist = to.length();
    if (dist > range) continue;

    const local = to.clone().applyQuaternion(inverse);
    result.push({
      localX: local.x,
      localY: local.y,
      localZ: local.z,
      dist: dist,
      decoyed: !!m.decoyed,          // 今フレアのほうを見ているか
    });
  }

  return result;
}

// ===================================================================
// 楕円体の当たり判定
//
// point(世界の座標)が、obj を中心とした楕円体の内側にあるかを返す。
// half は「機体から見た半分の大きさ」。
//
// やっていること:
//   1. 点を機体から見た座標に直す(worldToLocal)。
//      こうすると機体がどんな姿勢でも、まっすぐな箱の中の話になる。
//   2. 各軸を半径で割って、合計が1以下なら内側。
//      (x/a)² + (y/b)² + (z/c)² ≤ 1 が楕円体の式。
// ===================================================================
const _hitPoint = new THREE.Vector3();   // 毎回作らず使い回す

function hitsShip(point, obj, half, margin) {
  obj.updateMatrixWorld();
  _hitPoint.copy(point);
  obj.worldToLocal(_hitPoint);

  // margin は世界の単位で渡ってくる(近接信管の効く距離など)。
  // 判定は機体から見た座標で行うので、機体の拡大率でわって単位を合わせる。
  const m = (margin || 0) / (obj.scale.x || 1);
  const ax = half.x + m, ay = half.y + m, az = half.z + m;
  return (_hitPoint.x * _hitPoint.x) / (ax * ax)
       + (_hitPoint.y * _hitPoint.y) / (ay * ay)
       + (_hitPoint.z * _hitPoint.z) / (az * az) <= 1;
}

// ===================================================================
// 敵機への命中
// ===================================================================
// dealDamage が false のときは、見た目(光と破片)だけでHPは減らさない
function hitEnemy(e, point, dealDamage) {
  e.hitFlash = ENEMY.FLASH_SEC;         // 白く光らせる
  e.heatSig  = SENSOR.HEAT_LINGER;      // 被弾直後も熱くて見つかりやすい

  // 当たった場所で小さく閃光を出し、光る火花を飛ばす。
  // 暗い破片だけだと、当たったのかどうかが遠目に分からない。
  spawnFlash(point, 3.2, 0xfff0c0, 0.16);
  spawnDebris(point, DEBRIS.HIT_COUNT, DEBRIS.HIT_SIZE, DEBRIS.HIT_SPEED, 0xffd9a0, true);

  if (!dealDamage) return;

  e.hp -= 1;

  if (e.hp <= 0) {
    killEnemy(e);
  } else {
    setEnemyState(e, 'evade');   // 撃たれたら数秒逃げる(仕様の3状態目)
    // main.js 側のログ表示を呼ぶ(3Dは見た目、UIは main.js、と役割を分けている)
    onHit(e.hp);
  }
}

// ===================================================================
// 撃墜:機体を消し、破片をまき散らし、数秒後に別の位置へリスポーンさせる
// ===================================================================
// credit を false にすると撃墜数に数えない(敵どうしの衝突など)
function killEnemy(e, credit) {
  e.alive = false;
  e.group.visible = false;      // 空間からは消さず、見えなくするだけ(使い回すため)
  e.respawnLeft = ENEMY.RESPAWN_SEC;

  // 閃光 → 広がる輪 → 破片 の順に重ねる。
  // 3つとも同じ瞬間に出すが、消える速さが違うので目には順番に見える。
  spawnFlash(e.group.position, 26, 0xffffff, 0.26);
  spawnFlash(e.group.position, 15, 0xffb060, 0.46);
  spawnBlast(e.group.position, 13, 0xffc070);
  spawnDebris(e.group.position, 10, 0.30, DEBRIS.KILL_SPEED * 1.2, 0xffd9a0, true);   // 光る火花
  spawnDebris(e.group.position, DEBRIS.KILL_COUNT, DEBRIS.KILL_SIZE, DEBRIS.KILL_SPEED);
  if (credit !== false) onKill();
}

// ===================================================================
// 機体どうしの衝突
//
// これまで機体はすり抜けていた。宇宙で正面からぶつかって何も起きないのは
// さすがに嘘なので、当たったら両方とも爆散するようにする。
//
// 自機が巻き込まれた場合は即死にはしない ― シールドを吹き飛ばして
// HULLを1つ削る、という重い被弾として扱う。事故で一瞬で終わるより、
// 「やってしまった」と分かって立て直せるほうが操作の手応えが残る。
// ===================================================================
const COLLIDE = {
  PLAYER_RADIUS: 3.0,    // 自機の当たり半径
  SHIELD_DAMAGE:  70,    // 衝突で自機のシールドが受ける量
  SHAKE:         1.4,    // 衝突時の画面の揺れ
};

function updateCollisions() {
  // --- 自機 対 敵機 ---
  const reach = COLLIDE.PLAYER_RADIUS + ENEMY.HIT_RADIUS;
  for (const e of enemies) {
    if (!e.alive) continue;
    if (e.group.position.distanceTo(playerShip.position) > reach) continue;

    // 中間の点で爆発させる。どちらの機体でもない「ぶつかった場所」
    const mid = e.group.position.clone().add(playerShip.position).multiplyScalar(0.5);
    spawnFlash(mid, 40, 0xffffff, 0.34);
    spawnBlast(mid, 18, 0xffc070);
    spawnDebris(mid, 14, 0.32, DEBRIS.KILL_SPEED * 1.5, 0xffd9a0, true);

    killEnemy(e);            // 敵は撃墜として数える(自機がぶつけに行ったのだから)
    onPlayerCollide();       // main.js:自機側の被害
    return;                  // 1コマに1回で十分
  }

  // --- 敵機どうし ---
  // 撃墜数には数えない。こちらが仕留めたわけではないため。
  for (let i = 0; i < enemies.length; i++) {
    const a = enemies[i];
    if (!a.alive) continue;
    for (let j = i + 1; j < enemies.length; j++) {
      const b = enemies[j];
      if (!b.alive) continue;
      if (a.group.position.distanceTo(b.group.position) > ENEMY.HIT_RADIUS * 2) continue;

      const mid = a.group.position.clone().add(b.group.position).multiplyScalar(0.5);
      spawnFlash(mid, 34, 0xffffff, 0.30);
      spawnBlast(mid, 15, 0xffc070);
      killEnemy(a, false);
      killEnemy(b, false);
      onEnemyCollide();      // main.js:ログと音
      return;
    }
  }
}

// ===================================================================
// リスポーン:HPを戻し、前とは違う位置に出現させる
// ===================================================================
// forceType にタイプ名を渡すと抽選せずそのタイプで出す(出撃時の1機目用)
function respawnEnemy(e, forceType) {
  // 出てくるたびにタイプを引き直す。同じ相手が続かないので、
  // プレイヤーは「今度は何が来たか」を毎回見てから組み立てることになる。
  assignArchetype(e, forceType || pickArchetype());
  e.hp = e.arch.MAX_HP;
  e.alive = true;
  e.group.visible = true;
  e.respawnLeft = 0;

  // 自機は空間を移動していくので、リスポーン地点は「今の自機の前方」に取る。
  // そうしないと、飛び去ったあと遠い原点付近に湧いて見つけられなくなる。
  const forward = new THREE.Vector3(0, 0, -1).applyQuaternion(playerShip.quaternion);
  e.group.position.copy(playerShip.position)
    .addScaledVector(forward, 90)
    .add(new THREE.Vector3(
      (Math.random() - 0.5) * 40,
      (Math.random() - 0.5) * 24,
      (Math.random() - 0.5) * 40
    ));

  // AIを初期状態に戻す
  setEnemyState(e, 'approach');
  e.fireTimer = e.arch.FIRE.INTERVAL;
  e.telegraph = 0;
  // 位置が飛ぶので、速度の測定もやり直す(古い値を引きずらせない)
  if (e.vel) {
    e.vel.set(0, 0, 0); e.acc.set(0, 0, 0);
    e.prevVel.set(0, 0, 0); e.prevPos.copy(e.group.position);
  }

  e.heat = 0;
  e.burnLeft = 0;
  e.ventDown = 0;
  e.heatDown = 0;
  e.empLeft = 0;
  e.missileAmmo = e.arch.MISSILE.AMMO;
  // 最初の1発を撃つまでの時間は毎回ばらつかせる。
  // そろっていると2機が同時にロックしてきて、動きが機械的に見える。
  e.missileTimer = e.arch.MISSILE.INTERVAL * (0.35 + Math.random() * 0.5);
  e.missileTele = 0;
  e.missileBluff = false;
  e.flareAmmo = ENEMY_MISSILE.FLARE_AMMO;
  e.flareCool = 0;

  // 点滅の消し忘れがないよう、光をゼロに戻しておく
  e.hitFlash = 0;
  for (const material of e.materials) material.emissive.setRGB(0, 0, 0);
}

// ===================================================================
// 自機の爆散(MISSION FAILED の瞬間)
//
// 敵の撃墜と同じく破片をまき散らす。三人称なら自機が砕けるのが見え、
// コックピットなら破片が視界を横切っていく。
// 機体そのものは消さない ― リザルト画面の背景として残しておきたいため。
// ===================================================================
function explodePlayer() {
  if (!sceneReady) return;
  // 敵の撃墜より一回り大きく、長く光らせる
  spawnFlash(playerShip.position, 46, 0xffffff, 0.36);
  spawnFlash(playerShip.position, 28, 0xffa050, 0.70);
  spawnBlast(playerShip.position, 22, 0xffc070);
  spawnDebris(playerShip.position, 16, 0.34, DEBRIS.KILL_SPEED * 1.6, 0xffd9a0, true);
  spawnDebris(playerShip.position, DEBRIS.KILL_COUNT * 2, DEBRIS.KILL_SIZE * 1.3,
              DEBRIS.KILL_SPEED * 1.4);
  for (const glow of engineGlows) glow.material.opacity = 0;   // 噴射を止める
}

// ===================================================================
// 破片(デブリ)を撒く
// position=出る場所 / count=個数 / size=大きさ / speed=飛び散る速さ
// ===================================================================
// color / glow は省略できる。省略すると従来どおり「機体の破片」の色になる。
// glow=true にすると加算合成になり、自分で光っているもの(火の粉)として描かれる。
function spawnDebris(position, count, size, speed, color, glow) {
  // 四面体 = 三角形4枚。もっとも面数の少ない立体で、ローポリの破片にちょうどいい
  if (!debrisGeometry) debrisGeometry = new THREE.TetrahedronGeometry(1);

  for (let i = 0; i < count; i++) {
    // 破片ごとに薄れ方が違うので、材質は1個ずつ作る(透明度を個別に変えるため)
    const material = new THREE.MeshBasicMaterial({
      color: (color === undefined) ? ENEMY.EDGE_COLOR : color,
      transparent: true,     // 透明度を扱えるようにする
      opacity: 1,
      blending: glow ? THREE.AdditiveBlending : THREE.NormalBlending,
      depthWrite: !glow,
    });

    const mesh = new THREE.Mesh(debrisGeometry, material);
    mesh.position.copy(position);
    mesh.scale.setScalar(size * (0.5 + Math.random()));   // 大きさをばらつかせる

    // ランダムな方向へ、ばらついた速さで飛ばす
    const dir = new THREE.Vector3(
      Math.random() * 2 - 1,
      Math.random() * 2 - 1,
      Math.random() * 2 - 1
    ).normalize();   // 長さ1に揃える(そうしないと方向によって速さが変わる)

    const life = 0.6 + Math.random() * 0.8;

    debris.push({
      mesh: mesh,
      velocity: dir.multiplyScalar(speed * (0.4 + Math.random())),
      // 回転の速さもばらばらにすると、破片らしく見える
      spin: new THREE.Vector3(Math.random() - 0.5, Math.random() - 0.5, Math.random() - 0.5)
              .multiplyScalar(8),
      life: life,
      maxLife: life,
    });

    scene.add(mesh);
  }
}

// 破片を飛ばし、だんだん薄くして消す
function updateDebris(dt) {
  for (let i = debris.length - 1; i >= 0; i--) {
    const d = debris[i];

    d.mesh.position.addScaledVector(d.velocity, dt);
    d.velocity.multiplyScalar(1 - DEBRIS.DRAG * dt);   // だんだん減速

    d.mesh.rotation.x += d.spin.x * dt;
    d.mesh.rotation.y += d.spin.y * dt;
    d.mesh.rotation.z += d.spin.z * dt;

    d.life -= dt;
    // 残り寿命の割合をそのまま透明度に使う = だんだん消える
    d.mesh.material.opacity = Math.max(d.life / d.maxLife, 0);

    if (d.life <= 0) {
      scene.remove(d.mesh);
      d.mesh.material.dispose();   // 使い終わった材質を破棄(数が増えても重くならない)
      debris.splice(i, 1);
    }
  }
}

// ===================================================================
// 毎コマ呼ばれる更新+描画。dt=経過秒数 / elapsed=起動からの累計秒数
// ===================================================================
function updateScene(dt, elapsed) {
  if (!sceneReady) return;

  updateBolts(dt);
  updateMissiles(dt);
  updateFlares(dt);
  updateOrdnance(dt);   // ボム/EMPの飛翔と炸裂
  updateBlasts(dt);     // 炸裂の光
  updateEnemyBolts(dt);   // 敵の弾は敵が死んでいても飛び続ける
  updateDebris(dt);

  // 発光(被弾の白い点滅 と 発射予告の光)は、止まっていても消えていくよう常に更新する
  for (const e of enemies) updateEnemyGlow(e, dt);

  // 敵の速度は、戦闘が止まっていても測っておく。
  // 偏差照準がこれを使うので、未計測だと印が出なくなる。
  updateEnemyVelocity(dt);

  // --- ミッション終了中は戦闘を止める(破片だけ動かす)---
  if (combatFrozen) {
    renderer.render(scene, camera);
    renderRearMirror();
    return;
  }

  // --- 敵1機ずつ:死んでいればリスポーンを待ち、生きていればAIを動かす ---
  for (const e of enemies) {
    if (!e.alive) {
      e.respawnLeft -= dt;
      if (e.respawnLeft <= 0) respawnEnemy(e);
      continue;
    }
    updateEnemyAI(e, dt);
  }

  updateCollisions();   // 機体どうしがぶつかっていないか

  renderer.render(scene, camera);
  renderRearMirror();
}

// ===================================================================
// 後方確認ミラーを描く
//
// 本画面を描き終えたあとに呼ぶこと。
// setScissor で「この四角の中だけ描いてよい」と指示してから描くので、
// 本画面はそのまま残り、小窓の部分だけが後方の景色に置き換わる。
// ===================================================================
function renderRearMirror() {
  if (!MIRROR.ENABLED || !cockpitView) return;
  if (mirrorBroken) return;   // 壊れている = 何も描かない。枠の中はHTMLが塞ぐ

  const vw = window.innerWidth;
  const vh = window.innerHeight;
  const w = Math.round(vw * MIRROR.WIDTH);
  const h = Math.round(vh * MIRROR.HEIGHT);
  const x = Math.round((vw - w) / 2);                    // 横は中央
  // WebGL の座標は左下が原点。上端に置きたいので、上からの余白を下から測り直す
  const y = Math.round(vh - h - vh * MIRROR.TOP);

  // --- ミラーのカメラを、操縦席から後ろ向きに置く ---
  const eye = new THREE.Vector3(0, COCKPIT.EYE_UP, -COCKPIT.EYE_FORWARD)
    .applyQuaternion(playerShip.quaternion);
  mirrorCamera.position.copy(playerShip.position).add(eye);
  mirrorCamera.quaternion.copy(playerShip.quaternion);
  mirrorCamera.rotateY(Math.PI);        // 180度回して真後ろを向く

  mirrorCamera.aspect = w / h;
  mirrorCamera.updateProjectionMatrix();

  // 描く範囲を小窓に限定する。
  // setViewport = 描く場所 / setScissor = 塗ってよい範囲。両方を同じ四角にする。
  renderer.setScissorTest(true);
  renderer.setViewport(x, y, w, h);
  renderer.setScissor(x, y, w, h);
  renderer.render(scene, mirrorCamera);

  // 後片付け。戻さないと次のコマの本画面が小窓の大きさで描かれてしまう
  renderer.setScissorTest(false);
  renderer.setViewport(0, 0, vw, vh);
}

// ウィンドウサイズが変わったらカメラと描画サイズを合わせ直す
function onResize() {
  if (!sceneReady) return;
  camera.aspect = window.innerWidth / window.innerHeight;
  camera.updateProjectionMatrix();   // 縦横比を変えたら必ずこれを呼ぶ決まり
  renderer.setSize(window.innerWidth, window.innerHeight);
}
